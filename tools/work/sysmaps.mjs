// System maps in the Doodleverse layout (assets/images/doodleverse/system.svg): the product in the middle with its core loop,
// the people on the left, the things it runs on on the right, and what sits behind it along the bottom.
// Run: node sysmaps.mjs   → writes assets/images/<folder>/system-map.svg for each map below.
// Every line comes from the project's research and pages; nothing here is new data.
import { writeFileSync, mkdirSync } from "node:fs"

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
const INK = "#1f2233",
    SOFT = "#5b5f73",
    BODY = "#3d4052"
const PILLS = ["#fff1a6", "#ffd6e0", "#d3e8ff", "#d9f3cf"] // clockwise from top left

function card(x, y, c) {
    const lines = []
    lines.push(`<rect x="${x}" y="${y}" width="340" height="250" rx="26" fill="#fff" stroke="#e3e1ec" stroke-width="2" filter="url(#s)"/>`)
    const useLetter = c.letter && (x + 340 - 18 - (x + 92)) / (c.title.length * 0.6) >= 20
    const tx = useLetter ? x + 92 : x + 28
    if (useLetter) {
        lines.push(`<circle cx="${x + 52}" cy="${y + 56}" r="26" fill="${c.color}"/>`)
        lines.push(`<text x="${x + 52}" y="${y + 64}" text-anchor="middle" font-size="22" font-weight="700" fill="${INK}">${esc(c.letter)}</text>`)
    }
    // shrink a long title or sub-line so it stays inside the card
    const room = x + 340 - 18 - tx
    const tSize = Math.min(24, room / (c.title.length * 0.6))
    const sSize = Math.min(16, room / (c.sub.length * 0.5))
    lines.push(`<text x="${tx}" y="${y + 50}" font-size="${tSize.toFixed(1)}" font-weight="700" fill="${INK}">${esc(c.title)}</text>`)
    lines.push(`<text x="${tx}" y="${y + 76}" font-size="${sSize.toFixed(1)}" fill="${SOFT}">${esc(c.sub)}</text>`)
    c.bullets.forEach((b, i) => lines.push(`<text x="${x + 28}" y="${y + 132 + i * 30}" font-size="17" fill="${BODY}">• ${esc(b)}</text>`))
    return lines.join("\n  ")
}

const arrow = (d, dashed) => `<path d="${d}" stroke="${SOFT}" stroke-width="2.5"${dashed ? ' stroke-dasharray="7 6"' : ""} fill="none" marker-end="url(#a)"/>`
const label = (x, y, t, anchor = "middle", size = 15) =>
    String(t)
        .split("\n")
        .map((l, i) => `<text x="${x}" y="${y + i * 19}" text-anchor="${anchor}" font-size="${size}" fill="${SOFT}">${esc(l)}</text>`)
        .join("")
const above = (x, y, t) => {
    const ls = String(t).split("\n")
    return ls.map((l, i) => `<text x="${x}" y="${y - (ls.length - 1 - i) * 18}" text-anchor="middle" font-size="15" fill="${SOFT}">${esc(l)}</text>`).join("")
}
const around = (x, t) => {
    const ls = String(t).split("\n")
    return ls.length > 1 ? label(x, 632, ls[0], "middle", 14) + label(x, 668, ls[1], "middle", 14) : label(x, 632, t, "middle", 14)
}
const red = (x, y, t, anchor, accent) =>
    String(t)
        .split("\n")
        .map((l, i) => `<text x="${x}" y="${y + i * 20}" text-anchor="${anchor}" font-size="16" fill="${accent}">${esc(l)}</text>`)
        .join("")

function render(m) {
    const A = m.accent
    const pill = (x, y, t, fill) => {
        const w = Math.max(200, t.length * 12 + 40)
        return `<rect x="${x + 100 - w / 2}" y="${y}" width="${w}" height="74" rx="37" fill="${fill}"/><text x="${x + 100}" y="${y + 44}" fill="${INK}">${esc(t)}</text>`
    }
    const [L1, L2] = m.left,
        [R1, R2] = m.right
    const out = `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="912" viewBox="0 118 1600 912" font-family="'Helvetica Neue', Helvetica, Arial, sans-serif">
  <!-- ${esc(m.title)} system map, generated by tools/work/sysmaps.mjs -->
  <defs>
    <marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="9" markerHeight="9" orient="auto-start-reverse"><path d="M0 0L10 5L0 10z" fill="${SOFT}"/></marker>
    <marker id="r" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="9" markerHeight="9" orient="auto-start-reverse"><path d="M0 0L10 5L0 10z" fill="${A}"/></marker>
    <filter id="s" x="-10%" y="-10%" width="120%" height="130%"><feDropShadow dx="0" dy="6" stdDeviation="8" flood-color="#283060" flood-opacity=".12"/></filter>
  </defs>
  <rect y="118" width="1600" height="912" fill="#fbfaf7"/>

  <rect x="500" y="150" width="600" height="620" rx="32" fill="#fff" stroke="${A}" stroke-width="2.5" filter="url(#s)"/>
  <text x="800" y="200" text-anchor="middle" font-size="30" font-weight="700" fill="${INK}">${esc(m.title)}</text>
  <text x="800" y="232" text-anchor="middle" font-size="18" fill="${SOFT}">${esc(m.sub)}</text>
  <g font-size="21" font-weight="700" text-anchor="middle">
    ${pill(560, 290, m.loop[0], PILLS[0])}
    ${pill(840, 290, m.loop[1], PILLS[1])}
    ${pill(840, 530, m.loop[2], PILLS[2])}
    ${pill(560, 530, m.loop[3], PILLS[3])}
  </g>
  <g stroke="${A}" stroke-width="2.5" fill="none" marker-end="url(#r)">
    <path d="M762 327H836"/><path d="M940 366V526"/><path d="M838 567H764"/><path d="M660 528V368"/>
  </g>
  ${red(800, 279, m.edges[0], "middle", A)}
  ${red(924, 405, m.edges[1], "end", A)}
  ${red(800, 625, m.edges[2], "middle", A)}
  ${red(676, 490, m.edges[3], "start", A)}
  <text x="800" y="452" text-anchor="middle" font-size="17" font-weight="700" fill="${INK}">${esc(m.loopName)}</text>
  <rect x="540" y="670" width="520" height="66" rx="16" fill="#f3f1fb"/>
  ${m.strip.map((l, i) => `<text x="800" y="${698 + i * 23}" text-anchor="middle" font-size="16" fill="${SOFT}">${esc(l)}</text>`).join("")}

  ${card(60, 150, L1)}
  ${card(60, 520, L2)}
  ${card(1200, 150, R1)}
  ${card(1200, 520, R2)}

  ${m.a.l1in ? arrow("M402 245H496") + above(449, 235, m.a.l1in) : ""}
  ${m.a.l1out ? arrow("M496 305H404") + label(449, 330, m.a.l1out) : ""}
  ${m.a.l2 ? arrow(m.a.l2up ? "M230 518V404" : "M230 404V518", true) + label(244, 466, m.a.l2, "start") : ""}
  ${m.a.l2c ? arrow("M402 645H496", true) + around(449, m.a.l2c) : ""}
  ${m.a.r1in ? arrow("M1198 245H1104") + above(1151, 235, m.a.r1in) : ""}
  ${m.a.r1out ? arrow("M1104 305H1196") + label(1151, 330, m.a.r1out) : ""}
  ${m.a.r12 ? arrow("M1370 402V516") + label(1384, 466, m.a.r12, "start") : ""}
  ${m.a.r2in ? arrow("M1198 645H1104", true) + around(1151, m.a.r2in) : ""}
  ${m.a.r2out ? arrow("M1104 645H1196", true) + around(1151, m.a.r2out) : ""}

  <g font-size="17" fill="${BODY}">
    ${m.bottom
        .map((b, i) => {
            const x = [60, 570, 1080][i]
            return `<rect x="${x}" y="850" width="460" height="150" rx="22" fill="#f3f1fb"/><text x="${x + 28}" y="890" font-size="20" font-weight="700" fill="${INK}">${esc(b.title)}</text>${b.lines.map((l, k) => `<text x="${x + 28}" y="${924 + k * 28}">${esc(l)}</text>`).join("")}`
        })
        .join("\n    ")}
  </g>
  <g stroke="${SOFT}" stroke-width="2.5" fill="none" marker-end="url(#a)">
    <path d="M290 848C290 812 560 812 600 774"/><path d="M800 848V774"/><path d="M1310 848C1310 812 1040 812 1000 774"/>
  </g>
  ${label(370, 796, m.bottom[0].verb)}${label(862, 818, m.bottom[1].verb)}${label(1180, 806, m.bottom[2].verb)}
</svg>
`
    return out
}

